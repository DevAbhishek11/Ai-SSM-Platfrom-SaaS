/**
 * Local mock of the OpenAI, Anthropic, and Ollama HTTP contracts.
 * Used for manual end-to-end verification of provider routing without
 * requiring real credentials or network access.
 *
 *   node scripts/mock-ai-provider.mjs [port]
 */
import { createServer } from "node:http";

const port = Number(process.argv[2] ?? 8788);

function variantsFor(prompt) {
  const platforms = [...prompt.matchAll(/^- ([a-z]+): max/gm)].map((match) => match[1]);
  const targets = platforms.length > 0 ? platforms : ["linkedin"];

  return {
    variants: targets.map((platform) => ({
      platform,
      text: `[mock ${platform}] Coordinated launch copy generated by the mock provider for testing.`,
      hashtags: ["#MockProvider", "SocialOps"]
    }))
  };
}

function readBody(request) {
  return new Promise((resolve, reject) => {
    let raw = "";
    request.on("data", (chunk) => {
      raw += chunk;
    });
    request.on("end", () => {
      try {
        resolve(raw ? JSON.parse(raw) : {});
      } catch (error) {
        reject(error);
      }
    });
  });
}

const server = createServer(async (request, response) => {
  const url = request.url ?? "/";
  const json = (status, payload) => {
    response.writeHead(status, { "content-type": "application/json" });
    response.end(JSON.stringify(payload));
  };

  if (request.method === "GET") {
    if (url.startsWith("/api/tags")) {
      return json(200, { models: [{ name: "llama3.1" }] });
    }
    if (url.startsWith("/v1/models") || url.startsWith("/models")) {
      return json(200, { data: [{ id: "mock-model" }] });
    }
    return json(404, { error: "not found" });
  }

  const body = await readBody(request);
  const prompt =
    body.messages?.at(-1)?.content ??
    body.messages?.at(-1)?.content?.[0]?.text ??
    body.prompt ??
    "";
  const content = JSON.stringify(variantsFor(typeof prompt === "string" ? prompt : ""));

  if (url.startsWith("/v1/messages")) {
    const userMessage = body.messages?.at(-1)?.content;
    const text = Array.isArray(userMessage) ? (userMessage[0]?.text ?? "") : (userMessage ?? "");
    return json(200, {
      content: [{ type: "text", text: JSON.stringify(variantsFor(text)) }],
      usage: { input_tokens: 180, output_tokens: 260 }
    });
  }

  if (url.startsWith("/chat/completions") || url.startsWith("/v1/chat/completions")) {
    return json(200, {
      choices: [{ message: { role: "assistant", content } }],
      usage: { prompt_tokens: 175, completion_tokens: 240 }
    });
  }

  if (url.startsWith("/api/chat")) {
    return json(200, {
      message: { role: "assistant", content },
      prompt_eval_count: 150,
      eval_count: 220
    });
  }

  return json(404, { error: "not found" });
});

server.listen(port, "0.0.0.0", () => {
  console.log(`Mock AI provider listening on http://0.0.0.0:${port}`);
});
